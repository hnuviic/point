function tableBlock(num, title, headers, rows, intro, opts) {
  const blocks = [];
  if (intro) blocks.push(C.textParagraph(intro));
  blocks.push(C.tableCaption(`Таблица ${num} – ${title}`));
  blocks.push(C.dataTable(headers, rows, opts));
  blocks.push(new Paragraph({ spacing: { after: 160 }, children: [] }));
  return blocks;
}

function dbStructureBlock(num, tableName, rows, intro) {
  return tableBlock(num, `Структура «${tableName}»`, ['Поле', 'Тип', 'Ограничения', 'Описание'], rows, intro);
}

