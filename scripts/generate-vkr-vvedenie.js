const fs = require('fs');
const path = require('path');
const { Document, Packer } = require('docx');
const C = require('./vkr-doc-common');

const OUT_DIR = path.join(__dirname, '..', 'docs', 'vkr');

function introHeading(title) {
  return C.textParagraph(title, {
    center: true,
    bold: true,
    noIndent: true,
    size: C.SIZE_SECTION,
    before: 0,
    after: 300,
  });
}

function labeledParagraph(label, text) {
  const { Paragraph, TextRun, AlignmentType, LineRuleType } = require('docx');
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: C.LINE, lineRule: LineRuleType.AUTO, after: 0 },
    indent: { firstLine: C.INDENT },
    children: [
      new TextRun({ text: label, font: C.FONT, size: C.SIZE_BODY, bold: true }),
      new TextRun({ text, font: C.FONT, size: C.SIZE_BODY }),
    ],
  });
}

