async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const doc = new Document({
    sections: [
      C.makeSection([
        ...C.appendixBlock('Б', 'обязательное', 'Входные документы', buildBody()),
      ]),
    ],
  });

  const buffer = await Packer.toBuffer(doc);
  const outFile = path.join(OUT_DIR, 'Приложение_Б_Входные_документы.docx');
  await C.writeDoc(outFile, buffer);

  try {
    fs.writeFileSync(DESKTOP_COPY, buffer);
    console.log('Copied:', DESKTOP_COPY);
  } catch (err) {
    console.warn('Не удалось скопировать на рабочий стол:', err.message);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
