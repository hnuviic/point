async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const r = calc();
  const doc = new Document({
    sections: [
      C.makeSection([
        ...C.appendixBlock('А', 'обязательное', 'Расчёт экономической эффективности', buildBody(r)),
      ]),
    ],
  });

  const buffer = await Packer.toBuffer(doc);
  const outFile = path.join(OUT_DIR, 'Приложение_А_экономическая_эффективность.docx');
  await C.writeDoc(outFile, buffer);

  try {
    fs.writeFileSync(DESKTOP_COPY, buffer);
    console.log('Copied:', DESKTOP_COPY);
  } catch (err) {
    console.warn('Не удалось скопировать на рабочий стол:', err.message);
  }

  console.log('Итого затрат:', fmt(r.Sitogo, 0), 'руб.; цена:', fmt(r.Tsena, 0), 'руб.; Ток:', fmt(r.TokMes, 1), 'мес.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
