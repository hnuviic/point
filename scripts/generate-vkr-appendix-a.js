function fmt(n, digits = 2) {
  const v = typeof n === 'number' ? n : Number(n);
  const s = digits === 0 ? Math.round(v).toString() : v.toFixed(digits);
  const [int, dec] = s.split('.');
  const grouped = int.replace(/\B(?=(\d{3})+(?!\d))/g, '\u00a0');
  return dec ? `${grouped},${dec}` : grouped;
}

function calc() {
  const Dn = 30;
  const Htotal = 240;
  const Sdn = 1000;
  const Ndop = 80;
  const Kotch = 32.2;
  const Nn = 20;
  const Np = 30;
  const M = 1.5;
  const Twork = 6;
  const Skv = 5;
  const SnMes = 15000;

  const materials = [
    ['Доступ в Интернет', 'мес.', 3, 600, 1800],
    ['Аренда облачного сервера (Reg.ru, тестовый период)', 'мес.', 2, 1500, 3000],
    ['Регистрация домена pointdiscovery.online', 'год', 1, 800, 800],
    ['Флеш-накопитель (резервное копирование исходного кода)', 'шт.', 1, 650, 650],
    ['Канцелярские товары', 'шт.', 5, 70, 350],
    ['Бумага для печати документации', 'пачка', 1, 600, 600],
    ['Заправка картриджа', 'шт.', 1, 500, 500],
  ];
  const Zm = materials.reduce((s, row) => s + row[4], 0);

  const Zosn = Dn * Sdn;
  const Zdop = (Zosn * Ndop) / 100;
  const Znach = Zosn + Zdop;

  const Sv = (Znach * Kotch) / 100;
  const ZPF = (Znach * 24) / 100;
  const ZFOMS = (Znach * 5.1) / 100;
  const ZFSS = (Znach * 2.9) / 100;
  const ZNS = (Znach * 0.2) / 100;

  const Zn = ((Zosn + Zdop) * Nn) / 100;

  const R = M * Twork;
  const Zmash = R * Dn * Skv;

  const Sitogo = Zm + Zosn + Zdop + Sv + Zn + Zmash;
  const Tsena = Sitogo + (Znach * Np) / 100;

  const Egod = SnMes * 12;
  const Ecoef = Egod / Tsena;
  const TokMes = Tsena / SnMes;
  const TokGod = TokMes / 12;
  const Kef = 1 / TokGod;

  return {
    Dn,
    Htotal,
    Sdn,
    Ndop,
    Kotch,
    Nn,
    Np,
    M,
    Twork,
    Skv,
    SnMes,
    materials,
    Zm,
    Zosn,
    Zdop,
    Znach,
    Sv,
    ZPF,
    ZFOMS,
    ZFSS,
    ZNS,
    Zn,
    R,
    Zmash,
    Sitogo,
    Tsena,
    Egod,
    Ecoef,
    TokMes,
    TokGod,
    Kef,
  };
}

